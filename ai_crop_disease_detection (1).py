def generate_gradcam(image):

    grad_model = tf.keras.Model(
        inputs=base_model.input,
        outputs=[
            base_model.get_layer("top_conv").output,
            base_model.output
        ]
    )

    with tf.GradientTape() as tape:

        conv_outputs, features = grad_model(
            image,
            training=False
        )

        pooled = model.get_layer(
            "global_average_pooling2d"
        )(features)

        dropped = model.get_layer("dropout")(
            pooled,
            training=False
        )

        predictions = model.get_layer("dense")(dropped)

        class_index = tf.argmax(
            predictions[0]
        )

        class_score = predictions[:, class_index]

    gradients = tape.gradient(
        class_score,
        conv_outputs
    )

    weights = tf.reduce_mean(
        gradients,
        axis=(1, 2)
    )

    heatmap = tf.reduce_sum(
        weights[:, tf.newaxis, tf.newaxis, :]
        * conv_outputs,
        axis=-1
    )

    heatmap = tf.maximum(heatmap, 0)

    heatmap = heatmap[0]

    heatmap = heatmap / (
        tf.reduce_max(heatmap) + 1e-8
    )

    return heatmap.numpy(), int(class_index), predictions.numpy()[0]

